CREATE TABLE price_history (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
variant_id BIGINT NOT NULL,
old_price_amount NUMERIC(10, 2) NOT NULL,
old_price_currency VARCHAR(3) NOT NULL,
new_price_amount NUMERIC(10, 2) NOT NULL,
new_price_currency VARCHAR(3) NOT NULL,
changed_by VARCHAR(254) NOT NULL,
changed_at TIMESTAMPTZ NOT NULL,
CONSTRAINT fk_price_history_variant FOREIGN KEY (variant_id) REFERENCES product_variants (id) ON DELETE CASCADE
);

CREATE INDEX ix_price_history_variant_id ON price_history (variant_id);