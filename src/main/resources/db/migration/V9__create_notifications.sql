CREATE TABLE notifications (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT        NOT NULL REFERENCES user_accounts (id) ON DELETE CASCADE,
    price_change_id  BIGINT        NOT NULL REFERENCES price_history (id) ON DELETE CASCADE,
    product_slug     VARCHAR(80)   NOT NULL,
    message          VARCHAR(300)  NOT NULL,
    created_at       TIMESTAMPTZ   NOT NULL,
    read_at          TIMESTAMPTZ,
    CONSTRAINT uq_notifications_user_price_change UNIQUE (user_id, price_change_id)
);


CREATE INDEX ix_notifications_price_change_id ON notifications (price_change_id);