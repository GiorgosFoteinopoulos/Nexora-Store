CREATE TABLE product_variants (
id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
product_id BIGINT NOT NULL,
sku VARCHAR(32) NOT NULL,
colour VARCHAR(40) NOT NULL,
storage_gb INTEGER,
price_amount NUMERIC(10, 2) NOT NULL,
price_currency VARCHAR(3) NOT NULL,
stock INTEGER NOT NULL,
  CONSTRAINT fk_product_variants_product FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE CASCADE,
    CONSTRAINT uq_product_variants_sku UNIQUE (sku),
    CONSTRAINT ck_product_variants_stock CHECK (stock >= 0),
    CONSTRAINT ck_product_variants_storage CHECK (storage_gb IS NULL OR storage_gb > 0),
    CONSTRAINT ck_product_variants_price CHECK (price_amount >= 0)
);

CREATE INDEX ix_product_variants_product_id ON product_variants (product_id);