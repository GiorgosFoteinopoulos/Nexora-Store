CREATE TABLE products (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category    VARCHAR(20)   NOT NULL,
    name        VARCHAR(120)  NOT NULL,
    slug        VARCHAR(80)   NOT NULL,
    description VARCHAR(2000) NOT NULL,
    brand_id    BIGINT        NOT NULL,
    CONSTRAINT uq_products_slug UNIQUE (slug),
    CONSTRAINT fk_products_brand FOREIGN KEY (brand_id) REFERENCES brands (id),
    CONSTRAINT ck_products_category
        CHECK (category IN ('PHONE', 'LAPTOP', 'TABLET', 'WEARABLE', 'ACCESSORY'))
);


CREATE INDEX ix_products_brand_id ON products (brand_id);


CREATE TABLE phones (
    id            BIGINT PRIMARY KEY REFERENCES products (id) ON DELETE CASCADE,
    screen_inches DOUBLE PRECISION NOT NULL,
    battery_mah   INTEGER          NOT NULL,
    five_g        BOOLEAN          NOT NULL
);

CREATE TABLE laptops (
    id            BIGINT PRIMARY KEY REFERENCES products (id) ON DELETE CASCADE,
    screen_inches DOUBLE PRECISION NOT NULL,
    processor     VARCHAR(80)      NOT NULL,
    ram_gb        INTEGER          NOT NULL,
    weight_kg     DOUBLE PRECISION NOT NULL
);

CREATE TABLE tablets (
    id             BIGINT PRIMARY KEY REFERENCES products (id) ON DELETE CASCADE,
    screen_inches  DOUBLE PRECISION NOT NULL,
    stylus_support BOOLEAN          NOT NULL,
    cellular       BOOLEAN          NOT NULL
);

CREATE TABLE wearables (
    id                 BIGINT PRIMARY KEY REFERENCES products (id) ON DELETE CASCADE,
    battery_life_days  INTEGER NOT NULL,
    heart_rate_monitor BOOLEAN NOT NULL,
    gps                BOOLEAN NOT NULL
);


CREATE TABLE accessories (
    id BIGINT PRIMARY KEY REFERENCES products (id) ON DELETE CASCADE
);

CREATE TABLE accessory_categories (
    accessory_id BIGINT      NOT NULL REFERENCES accessories (id) ON DELETE CASCADE,
    category     VARCHAR(20) NOT NULL,
    PRIMARY KEY (accessory_id, category),
    CONSTRAINT ck_accessory_categories_category
        CHECK (category IN ('PHONE', 'LAPTOP', 'TABLET', 'WEARABLE'))
);